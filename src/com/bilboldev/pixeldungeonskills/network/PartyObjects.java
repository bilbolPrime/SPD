    private PartyObjects() { }

    @SafeVarargs
    private static void add(Class<? extends Bundlable>... types) {
        for (Class<? extends Bundlable> type : types) objects.put(type.getName(), type);
    }

    @SafeVarargs
    private static void sprites(Class<? extends CharSprite>... types) {
        for (Class<? extends CharSprite> type : types) sprites.put(type.getName(), type);
    }

    static Class<? extends Bundlable> type(String name) {
        Class<? extends Bundlable> type = objects.get(name);
        if (type == null) throw new IllegalArgumentException("Unsupported party object");
        return type;
    }

    static void item(String name) {
        if (!Item.class.isAssignableFrom(type(name))) throw new IllegalArgumentException("Invalid quick slot type");
    }

    static void sprite(String name) {
        if (!sprites.containsKey(name)) throw new IllegalArgumentException("Invalid pet sprite");
    }

    @SafeVarargs
    private static void equipmentBuffs(Class<? extends Bundlable>... types) {
        add(types);
        for (Class<?> type : types) equipmentBuffs.add(type);
    }

    static Bundlable create(String name) {
        try {
            Class<? extends Bundlable> type = type(name);

            if (equipmentBuffs.contains(type)) return null;
            return type.getConstructor().newInstance();
        } catch (ReflectiveOperationException invalid) {
            throw new IllegalArgumentException("Could not restore party object", invalid);
        }
    }
